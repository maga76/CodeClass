LANGUAGE_FILES = {'python': 'solution.py', 'cpp': 'main.cpp', 'html': 'index.html'}
LANGUAGE_ICONS = {'python': 'terminal', 'cpp': 'code', 'html': 'globe'}


@register.simple_tag
def icon(name, extra_class=''):
    return mark_safe(
        f'<svg class="icon {extra_class}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{ICONS[name]}</svg>'
    )


@register.simple_tag
def lang_badge(task):
    return mark_safe(
        f'<span class="badge lang-{task.language}">{icon(LANGUAGE_ICONS[task.language])}'
        f'{task.get_language_display()}</span>'
    )


@register.filter
def score_class(score):
    """CSS-класс для цвета балла: зелёный, жёлтый или красный."""
    if score is None:
        return ''
    if score >= 8:
        return 'score-high'
    if score >= 5:
        return 'score-mid'
    return 'score-low'


@register.filter
def initials(user):
    name = f'{user.first_name[:1]}{user.last_name[:1]}' or user.username[:2]
    return name.upper()


@register.filter
def filename(language):
    return LANGUAGE_FILES.get(language, 'code.txt')


@register.filter
def cover(pk):
    """Один из четырёх градиентов обложки класса — по номеру класса."""
    return f'cover-{pk % 4}'


@register.filter
def percent(value, total):
    return round(value / total * 100) if total else 0
